export function getDailyHadith(): Hadith {
  const today = new Date();
  const dayOfYear = Math.floor((today.getTime() - new Date(today.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24));
  return HADITHS[dayOfYear % HADITHS.length];
}

export function getHadithByCategory(category: string): Hadith[] {
  return HADITHS.filter(h => h.category === category);
}

export function getHadithCategories(): string[] {
  return [...new Set(HADITHS.map(h => h.category))];
}
